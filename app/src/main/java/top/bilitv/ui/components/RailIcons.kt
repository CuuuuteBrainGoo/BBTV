/**
 * 侧栏与「我的」页用的一组线性图标。
 *
 * ## 为什么自己画，而不是引一个图标库
 *
 * 少爷 2026-09-29 的要求：
 * > 图标需参照 **B 站对应功能的官方图标风格与样式**；B 站没有对应图标、需自行绘制的情况，
 * > 绘制风格**必须与 B 站已有图标保持一致**。
 *
 * 引第三方图标库解决不了这个要求 —— 我们要的不是"有图标用"，是**和 B 站的笔画一致**。
 * 而 B 站官方图标的共同特征很清楚：**线性、等宽描边、圆头圆角、无填充**。
 * 所以这里手绘，量规写在 `docs/32`：
 * **24×24 网格 / 活动区 20 / 描边 2 / 圆头端点 / 圆角连接 / 无填充 / 单图标 ≤12 段**。
 *
 * ⛔ **不要照抄 `design/proto 下的 html 原型` 里的占位字符**（`⌂ ▣ ◈ ◷ ◉ ☺ ◎ ◐ ⚙`）——
 * 其中 `☺`(U+263A) 和 `⚙`(U+2699) 落在 P0 禁用的 `[\x{2600}-\x{26FF}]` 区间内，
 * 照抄会直接打红我们自己的门禁。**权威是"原型的意图"，不是"原型的每一个字符"。**
 *
 * ## 每个图形照着哪张参考定的（少爷 2026-09-29 给的截图）
 *
 * | 图标 | 参照 |
 * |---|---|
 * | [Dynamic] `动态` | B 站官方**四叶风车**（不是星芒，我第一版画错了） |
 * | [History] `历史` | B 站官方**时钟** |
 * | [Mine] `我的` | B 站官方**小电视**（两根天线 + 两条竖杠眼睛），不是"单人" |
 * | [Settings] `设置` | B 站官方**六边形 + 内圆**，不是齿轮 |
 * | [Live] `直播` | 摄像机机身 + 镜头 + 录制圆点（参照给的那组 LIVE 标签） |
 * | [Star] `收藏` | B 站官方**五角星**（用在「我的」页，不在侧栏） |
 *
 * ## 落地写法：直接吃 SVG 的 d 字符串
 *
 * 用 [addPathNodes] 解析路径串，**不手写 `moveTo/lineTo` 坐标** ——
 * 设计稿改一个点，这里改一个字符，两边一一对应。
 * 颜色交给 `Icon(tint = ...)` 覆盖（见 [icon] 里的占位色说明），
 * 所以"常态/当前页/焦点"三种状态**只需要换 tint，不需要三套资源**。
 */
object RailIcons {

    /**
     * 把一个或多个 SVG `d` 串组装成线性图标。
     *
     * 描边色用 `Color.Black` 只是**占位** —— `Icon(imageVector, tint = X)`
     * 会用 ColorFilter 把所有非透明像素换成 X，所以真实颜色在调用侧决定。
     */
    private fun icon(name: String, vararg paths: String): ImageVector =
        ImageVector.Builder(
            name = name,
            defaultWidth = ICON_SIZE,
            defaultHeight = ICON_SIZE,
            viewportWidth = 24f,
            viewportHeight = 24f,
        ).apply {
            paths.forEach { d ->
                addPath(
                    pathData = addPathNodes(d),
                    fill = null,
                    stroke = SolidColor(Color.Black),
                    strokeLineWidth = STROKE,
                    strokeLineCap = StrokeCap.Round,
                    strokeLineJoin = StrokeJoin.Round,
                )
            }
        }.build()

