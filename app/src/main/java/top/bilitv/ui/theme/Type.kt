package top.bilitv.ui.theme

import androidx.compose.ui.unit.sp

/*
 * ════════════════════════════════════════════════════════════════════════════
 * 字号阶梯 —— **全项目唯一的一份**
 * ════════════════════════════════════════════════════════════════════════════
 *
 * ## 为什么要有这个文件
 *
 * 收编之前，`ui/` 下面散着 **119 处 `fontSize = <数字>.sp`**、**18 个不同的字号**，
 * 没有一处能看出"这个 15sp 和那个 15sp 是不是同一个层级的字"。
 *
 * 后果不是"不好看"，而是**改不动**：
 * - 想调一档"卡片副标题"的粗细，得先 grep 出 18 处 15sp、再人工判断哪些是副标题、
 *   哪些只是碰巧写了 15 —— **一次改动要开十几个文件，还必然漏几个**；
 * - 字号是**成对**用的（`fontSize` 和 `lineHeight` 必须一起改，`docs/99` §E 记过
 *   "只改 fontSize 会叠字"）。散着写的时候，这条规则只能靠记性守。
 *
 * ## 收编的方式：**只改名，不改值**
 *
 * 这一步**刻意不动任何数值** —— 每个 token 的值就是它替换掉的那个数字。
 * 所以这次改动**视觉上零变化**，唯一的收益是：
 * **以后要调字号，只动这一个文件。**
 *
 * ⚠️ 想"顺手合并掉几个相近档位"（比如 13/14/15 合成一个）**是另一件事**，
 * 那一定会改视觉，必须对着屏幕一档一档看。**别混在这一步里做。**
 *
 * ## 阶梯（从大到小）
 *
 * | token | 值 | 用在哪 |
 * |---|---|---|
 * | [Hero] | 40sp | 影院主视觉大标题（全项目最大；是卡片标题的两倍多，层级感靠这个差距） |
 * | [Mega] | 36sp | 一级页大标题的强调档 |
 * | [Jumbo] | 30sp | 一级页大标题（「我的」那一类） |
 * | [Big] | 28sp | 大标题的次一档 |
 * | [H1] | 26sp | 页面标题（设置 / 收藏 / 历史 / 关注 / 动态 / 直播） |
 * | [H2] | 24sp | 分区小标题、卡片大标题 |
 * | [H3] | 22sp | 弹窗/面板标题 |
 * | [H4] | 20sp | 区块标题（「为你精选」「全部电影」） |
 * | [CardTitle] | 18sp | 视频卡片标题（BT 实测值） |
 * | [Body1] | 17sp | 设置项标题、正文强调 |
 * | [Body2] | 16sp | 按钮文字、正文 |
 * | [Body3] | 15sp | 次要正文、次级按钮 |
 * | [Meta] | 14sp | 卡片元信息（UP 主 / 日期） |
 * | [Caption] | 13sp | 说明文字、角标 |
 * | [Small] | 12sp | 提示文字、交互说明 |
 * | [Tiny] | 11sp | 图上小角标 |
 * | [Micro] | 10sp | 极少数最小说明 |
 *
 * ⚠️ **这些值不随皮肤变**（不在 [BiliTheme] 里）：字号阶梯是**产品层级**，
 * 不是皮肤的一部分。两套皮肤换的是颜色、间距、列数，字号不变 ——
 * 换了字号，"这是标题那是正文"的层级关系就跟着变了，那不是皮肤该管的事。
 */
object AppType {
    val Hero = 40.sp
    val Mega = 36.sp
    val Jumbo = 30.sp
    val Big = 28.sp
    val H1 = 26.sp
    val H2 = 24.sp
    val H3 = 22.sp
    val H4 = 20.sp
    val CardTitle = 18.sp
    val Body1 = 17.sp
    val Body2 = 16.sp
    val Body3 = 15.sp
    val Meta = 14.sp
    val Caption = 13.sp
    val Small = 12.sp
    val Tiny = 11.sp
    val Micro = 10.sp
}
